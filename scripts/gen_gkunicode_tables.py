#!/usr/bin/env python3
"""Generate the C tables for the Unicode-native cruncher input path (Round 19.4).

The reference converter is ``morpheus_toolkit.beta.to_beta`` + the runner's
``_normalize_beta``:

    apostrophe translation (U+2019/2018/02BC/00B4 -> ') -> word-final U+0313
    -> ' -> ``beta_code.greek_to_beta_code`` -> ``.lower()``

and ``greek_to_beta_code`` is exactly: NFC normalize, look every codepoint up in
the beta-code package's ``unicode_to_beta_code.json``, pass unmapped characters
through. This script serializes that behavior for C (``src/anal/gkunicode_tab.c``):

  * the single-codepoint beta map (all single-character keys of the package
    JSON; its three space+combining-mark keys cannot occur inside a word);
  * NFC composition pairs, derived by asking ``unicodedata`` for every
    (starter, combining mark) combination over the Greek ranges, so the C
    composition matches Unicode NFC for Greek input;
  * combining classes (U+0300-U+036F) for canonical ordering;
  * Unicode lowercase mappings for pass-through Greek codepoints (the Python
    reference lowercases the whole converted string).

Re-run after upgrading the beta-code package; the generated file records the
package JSON's path, size and hash so drift is detectable.
"""
from __future__ import annotations

import hashlib
import json
import os
import sys
import unicodedata as ud

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

try:
    import beta_code
except ImportError:
    sys.path.insert(0, os.path.join(REPO, "python"))
    import beta_code


def main() -> int:
    source = os.path.join(os.path.dirname(beta_code.__file__),
                          "vendor", "beta-code-json", "unicode_to_beta_code.json")
    with open(source, encoding="utf-8") as handle:
        raw = handle.read()
    data = json.loads(raw)
    digest = hashlib.sha256(raw.encode("utf-8")).hexdigest()[:16]

    single = {ord(key): value for key, value in data.items() if len(key) == 1}

    # Canonical decomposition (NFD) of every codepoint that can appear as
    # input: NFC applies full decomposition before recomposition, and singleton
    # decompositions (U+0340 -> U+0300, U+0343 -> U+0313, U+0344 -> U+0308
    # U+0301) are not composition pairs.
    nfd_scope = sorted(set(range(0x0300, 0x0370)) | set(range(0x0370, 0x0400))
                       | set(range(0x1F00, 0x2000)) | set(single))
    nfd = []
    for cp in nfd_scope:
        decomposed = ud.normalize("NFD", chr(cp))
        if decomposed != chr(cp):
            if len(decomposed) > 4:
                raise SystemExit(f"NFD too long for U+{cp:04X}")
            nfd.append((cp, [ord(c) for c in decomposed]))
    # Decomposition pieces (including spacing characters such as U+00A8 or the
    # backtick) can start a recomposition, so they must be pair starters.
    pieces = {piece for _cp, seq in nfd for piece in seq}

    # NFC composition pairs: starters = every mapped codepoint, the Greek and
    # Greek Extended blocks, and every decomposition piece, so recomposition
    # after NFD matches unicodedata's NFC exactly for Greek input.
    starters = sorted(set(single)
                      | set(range(0x0370, 0x0400))
                      | set(range(0x1F00, 0x2000))
                      | pieces)
    marks = list(range(0x0300, 0x0370))
    pairs = set()
    for starter in starters:
        for mark in marks:
            composed = ud.normalize("NFC", chr(starter) + chr(mark))
            if len(composed) == 1 and ord(composed) != starter:
                pairs.add((starter, mark, ord(composed)))
    pairs = sorted(pairs)

    ccc = sorted((mark, ud.combining(chr(mark))) for mark in marks
                 if ud.combining(chr(mark)))

    lower_codepoints = sorted(
        set(range(0x0300, 0x0370)) | set(range(0x0370, 0x0400))
        | set(range(0x1F00, 0x2000)) | set(single)
        | {0x2019, 0x2018, 0x02BC, 0x00B4, 0x2014, 0x00B7, 0x02B9, 0x02BD}
    )
    lowers = []
    for cp in lower_codepoints:
        char = chr(cp)
        lowered = char.lower()
        if lowered != char and len(lowered) == 1:
            lowers.append((cp, ord(lowered)))

    lines = [
        "/* Generated by scripts/gen_gkunicode_tables.py - do not edit.",
        f" * beta-code package map: {os.path.basename(source)}",
        f" * sha256[:16]={digest} ({len(data)} entries; "
        f"{len(single)} single-codepoint keys)",
        f" * NFC composition pairs: {len(pairs)}; "
        f"combining marks: {len(ccc)}; lowercase mappings: {len(lowers)}; "
        f"NFD expansions: {len(nfd)}",
        " */",
        '#include "gkunicode_tab.h"',
        "",
        "const gkuni_map_entry gkuni_map[] = {",
    ]
    for cp, value in sorted(single.items()):
        lines.append(f"  {{0x{cp:04X}, {json.dumps(value)}}},")
    lines += ["};", f"const int gkuni_map_len = {len(single)};", ""]

    lines.append("const gkuni_comp_entry gkuni_comp[] = {")
    for starter, mark, result in pairs:
        lines.append(f"  {{0x{starter:04X}, 0x{mark:04X}, 0x{result:04X}}},")
    lines += ["};", f"const int gkuni_comp_len = {len(pairs)};", ""]

    lines.append("const gkuni_ccc_entry gkuni_ccc[] = {")
    for mark, value in ccc:
        lines.append(f"  {{0x{mark:04X}, {value}}},")
    lines += ["};", f"const int gkuni_ccc_len = {len(ccc)};", ""]

    lines.append("const gkuni_lower_entry gkuni_lower[] = {")
    for cp, lowered in lowers:
        lines.append(f"  {{0x{cp:04X}, 0x{lowered:04X}}},")
    lines += ["};", f"const int gkuni_lower_len = {len(lowers)};", ""]

    lines.append("const gkuni_nfd_entry gkuni_nfd[] = {")
    for cp, decomposed in nfd:
        slots = ", ".join(f"0x{c:04X}" for c in decomposed)
        lines.append(f"  {{0x{cp:04X}, {{{slots}, 0}}}},")
    lines += ["};", f"const int gkuni_nfd_len = {len(nfd)};", ""]

    out = os.path.join(REPO, "src", "anal", "gkunicode_tab.c")
    with open(out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {out}: map {len(single)}, pairs {len(pairs)}, "
          f"ccc {len(ccc)}, lower {len(lowers)}, nfd {len(nfd)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
